#Requires -Version 7.0
param([switch]$NoBrowser)

$ErrorActionPreference = 'Stop'
$PSNativeCommandUseErrorActionPreference = $false
$projectRoot = Split-Path -Parent $PSScriptRoot
$backendRoot = Join-Path $projectRoot 'backend'
$frontendRoot = Join-Path $projectRoot 'frontend'
$port = 8000
$demoUrl = "http://127.0.0.1:$port/team"

function Invoke-Python([string]$Step, [string[]]$Arguments) {
    & $python @Arguments
    if ($LASTEXITCODE -ne 0) {
        throw "$Step 失败（退出码 $LASTEXITCODE）。"
    }
}

Push-Location -LiteralPath $backendRoot
$previousEnv = @{}
$launchLock = [Threading.Mutex]::new($false, 'Local\CampusClaimDemo-8000')
$ownsLock = $false
try {
    try {
        $ownsLock = $launchLock.WaitOne(0)
    } catch [Threading.AbandonedMutexException] {
        $ownsLock = $true
    }
    if (-not $ownsLock) {
        throw '演示服务正在启动或运行，请查看已有的启动窗口。'
    }

    $listener = [Net.Sockets.TcpListener]::new([Net.IPAddress]::Loopback, $port)
    $listener.ExclusiveAddressUse = $true
    try {
        $listener.Start()
    } catch [Net.Sockets.SocketException] {
        throw "端口 $port 无法使用。请关闭占用端口的程序后重试。"
    } finally {
        $listener.Stop()
    }

    $venvRoot = Join-Path $projectRoot '.venv'
    $venvPython = Join-Path $venvRoot 'Scripts\python.exe'
    if (Test-Path -LiteralPath $venvPython -PathType Leaf) {
        $python = $venvPython
    } else {
        $command = Get-Command python.exe -CommandType Application -ErrorAction SilentlyContinue |
            Select-Object -First 1
        if (-not $command) {
            throw '请先安装 Python 3.11 或更新版本，并将 Python 加入 PATH。'
        }
        $python = $command.Source
    }
    & $python -c 'import sys; sys.exit(sys.version_info < (3, 11))'
    if ($LASTEXITCODE -ne 0) {
        throw '需要 Python 3.11 或更新版本。'
    }

    & $python -c 'import django, rest_framework, pymysql, cryptography, PIL' 2>$null
    if ($LASTEXITCODE -ne 0) {
        Write-Host '正在安装项目依赖…'
        if ($python -ne $venvPython) {
            Invoke-Python '创建 Python 虚拟环境' @('-m', 'venv', $venvRoot)
            $python = $venvPython
        }
        Invoke-Python '安装 Python 依赖' @('-m', 'pip', 'install', '-r', 'requirements.txt')
    }

    $npm = Get-Command npm.cmd -CommandType Application -ErrorAction SilentlyContinue | Select-Object -First 1
    if (-not $npm) {
        throw '请先安装 Node.js 和 npm。'
    }
    $frontendLock = Get-Item -LiteralPath (Join-Path $frontendRoot 'package-lock.json')
    $installedLockPath = Join-Path $frontendRoot 'node_modules\.package-lock.json'
    $installedLock = Get-Item -LiteralPath $installedLockPath -ErrorAction SilentlyContinue
    if (-not $installedLock -or $installedLock.LastWriteTimeUtc -lt $frontendLock.LastWriteTimeUtc) {
        Write-Host '正在安装前端依赖…'
        & $npm.Source --prefix $frontendRoot ci --include=dev
        if ($LASTEXITCODE -ne 0) { throw "安装前端依赖失败（退出码 $LASTEXITCODE）。" }
    }
    Write-Host '正在构建联调页面…'
    & $npm.Source --prefix $frontendRoot run build
    if ($LASTEXITCODE -ne 0) { throw "构建联调页面失败（退出码 $LASTEXITCODE）。" }

    # Use the local .env generated by the database script, even from a shell used for testing.
    foreach ($name in 'APP_ENV', 'DATABASE_URL', 'AUTH_SECRET', 'DEMO_MODE', 'DJANGO_SETTINGS_MODULE') {
        $previousEnv[$name] = [Environment]::GetEnvironmentVariable($name)
        Remove-Item -LiteralPath "Env:$name" -ErrorAction SilentlyContinue
    }
    $env:APP_ENV = 'dev'

    Write-Host '正在启动项目专用 MySQL…'
    & (Join-Path $PSScriptRoot 'local_mysql.ps1') -Action Start
    $checkDatabase = @'
import os

os.environ.setdefault("DJANGO_SETTINGS_MODULE", "config.settings")
import django

django.setup()
from django.conf import settings

db = settings.DATABASES["default"]
target = (db["ENGINE"], db["HOST"], db["PORT"], db["NAME"])
expected = ("django.db.backends.mysql", "127.0.0.1", "33307", "claim_dev")
if target != expected or not settings.DEMO_MODE:
    raise SystemExit("演示服务需要 127.0.0.1:33307 的隔离库 claim_dev，且 DEMO_MODE=true。")
'@
    Invoke-Python '校验本地演示数据库' @('-c', $checkDatabase)
    Invoke-Python '应用数据库迁移' @('manage.py', 'migrate', '--noinput')
    Invoke-Python '准备联调演示数据' @('manage.py', 'seed_team_demo')

    Write-Host "联调页面 $demoUrl"
    Write-Host '请保留此窗口。按 Ctrl+C 停止网页服务。'
    $runServer = @'
import os
import sys
import threading
import time
import urllib.request
import webbrowser

os.environ.setdefault("DJANGO_SETTINGS_MODULE", "config.settings")
from django.core.management import execute_from_command_line

port = int(sys.argv[1])
action = sys.argv[2]


def open_when_ready():
    for _ in range(600):
        try:
            urllib.request.urlopen(f"http://127.0.0.1:{port}/health", timeout=0.5).close()
            webbrowser.open(f"http://127.0.0.1:{port}/team")
            return
        except Exception:
            time.sleep(0.1)


if action == "open":
    threading.Thread(target=open_when_ready, daemon=True).start()
execute_from_command_line(["manage.py", "runserver", f"127.0.0.1:{port}", "--noreload"])
'@
    $browserAction = if ($NoBrowser) { 'skip' } else { 'open' }
    $runServer | & $python - $port $browserAction
    if ($LASTEXITCODE -ne 0) {
        throw "网页服务启动失败（退出码 $LASTEXITCODE）。"
    }
} catch {
    Write-Host "启动失败。$($_.Exception.Message)" -ForegroundColor Red
    exit 1
} finally {
    foreach ($name in $previousEnv.Keys) {
        if ($null -eq $previousEnv[$name]) {
            Remove-Item -LiteralPath "Env:$name" -ErrorAction SilentlyContinue
        } else {
            [Environment]::SetEnvironmentVariable($name, $previousEnv[$name])
        }
    }
    if ($ownsLock) {
        $launchLock.ReleaseMutex()
    }
    $launchLock.Dispose()
    Pop-Location
}
